import React from 'react';
import { 
  ArrowLeft, Sliders, BrainCircuit, Sparkles, AlertCircle, CheckCircle2, 
  Printer, TrendingUp, TrendingDown, Scale, ShieldAlert, Cpu, Layers, Download
} from 'lucide-react';
import CircularGauge from '../components/CircularGauge';

export default function PredictionResultsPage({ 
  predictionResult, 
  setActivePage,
  setWhatIfBaseline
}) {
  if (!predictionResult) {
    return (
      <div className="max-w-2xl mx-auto py-16 text-center space-y-4">
        <div className="w-16 h-16 rounded-2xl bg-amber-100 text-amber-700 flex items-center justify-center mx-auto">
          <AlertCircle className="w-8 h-8" />
        </div>
        <h2 className="text-xl font-bold text-slate-800">No Assessment Found</h2>
        <p className="text-xs text-slate-500">
          Please complete the patient assessment form to generate a live model risk prediction.
        </p>
        <button
          onClick={() => setActivePage('assessment')}
          className="px-5 py-2.5 rounded-xl bg-teal-600 text-white text-xs font-bold hover:bg-teal-700 shadow-sm"
        >
          Go to Risk Assessment
        </button>
      </div>
    );
  }

  const { 
    probability_percentage, decision_threshold_percentage,
    risk_classification, model_name, top_risk_increasing_factors,
    top_protective_factors, engineered_features, actionable_recommendations,
    inputSnapshot 
  } = predictionResult;

  const handleLaunchWhatIf = () => {
    if (setWhatIfBaseline && inputSnapshot) {
      setWhatIfBaseline(inputSnapshot);
    }
    setActivePage('what-if');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadJSON = () => {
    const reportData = {
      project_title: "Inherited-Susceptibility-Aware Lifestyle Risk Modelling for Personalized Type-2 Diabetes Prediction",
      export_timestamp: new Date().toISOString(),
      evaluation_summary: {
        model_name: model_name,
        estimated_probability_percentage: probability_percentage,
        decision_threshold_percentage: decision_threshold_percentage,
        classification_result: risk_classification.level,
        description: risk_classification.description
      },
      patient_input_snapshot: inputSnapshot,
      domain_engineered_indices: engineered_features,
      top_risk_increasing_factors: top_risk_increasing_factors,
      top_protective_factors: top_protective_factors,
      lifestyle_recommendations: actionable_recommendations,
      academic_disclaimer: "This report is generated by an academic machine learning prototype for research evaluation (Review III). It is not a clinical medical diagnosis or therapeutic prescription."
    };

    const blob = new Blob([JSON.stringify(reportData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `diabetes_risk_report_${new Date().toISOString().slice(0, 10)}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-4xl mx-auto space-y-8 py-4">
      
      {/* Top Banner & Action Controls */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <span className="text-xs font-bold text-teal-600 uppercase tracking-wider">
            Evaluation Report
          </span>
          <h1 className="text-2xl font-extrabold text-slate-900 tracking-tight mt-0.5">
            Type-2 Diabetes Risk Analysis
          </h1>
        </div>

        <div className="flex items-center space-x-2">
          <button
            onClick={() => setActivePage('assessment')}
            className="inline-flex items-center space-x-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold text-slate-600 bg-white border border-slate-200 hover:bg-slate-50 transition-colors shadow-sm"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>Edit Assessment</span>
          </button>

          <button
            onClick={handleLaunchWhatIf}
            className="inline-flex items-center space-x-1.5 px-3.5 py-2 rounded-xl text-xs font-bold text-white bg-teal-600 hover:bg-teal-700 transition-colors shadow-sm"
          >
            <Sliders className="w-3.5 h-3.5" />
            <span>Launch What-If Simulator</span>
          </button>

          <button
            onClick={handleDownloadJSON}
            className="inline-flex items-center space-x-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold text-slate-600 bg-white border border-slate-200 hover:bg-slate-50 transition-colors shadow-sm"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download Report</span>
          </button>

          <button
            onClick={handlePrint}
            className="inline-flex items-center space-x-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold text-slate-600 bg-white border border-slate-200 hover:bg-slate-50 transition-colors shadow-sm"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print PDF</span>
          </button>
        </div>
      </div>

      {/* Main Prediction Score Card */}
      <div className="bg-white rounded-3xl p-6 sm:p-8 border border-slate-200 shadow-sm grid grid-cols-1 md:grid-cols-12 gap-8 items-center">
        
        {/* Gauge Column */}
        <div className="md:col-span-5 flex flex-col items-center justify-center p-4 bg-slate-50 rounded-2xl border border-slate-100">
          <CircularGauge
            percentage={probability_percentage}
            threshold={decision_threshold_percentage}
            riskLabel={risk_classification.level}
            badgeColor={risk_classification.badge_color}
          />
          <div className="mt-4 text-center space-y-1">
            <span className="text-[11px] font-mono text-slate-500">
              Optimal F1 Threshold: <strong className="text-slate-700">{decision_threshold_percentage}%</strong>
            </span>
            <p className="text-[10px] text-slate-400">
              Cohort Baseline Prevalence: 14.5%
            </p>
          </div>
        </div>

        {/* Narrative & Model Info Column */}
        <div className="md:col-span-7 space-y-4">
          <div className="flex items-center space-x-2">
            <Cpu className="w-4 h-4 text-teal-600" />
            <span className="text-xs font-bold text-slate-600 uppercase font-mono">
              {model_name}
            </span>
          </div>

          <h2 className="text-xl sm:text-2xl font-extrabold text-slate-900 tracking-tight">
            Classification: <span className={
              risk_classification.badge_color === 'rose' ? 'text-rose-600' :
              risk_classification.badge_color === 'amber' ? 'text-amber-600' :
              risk_classification.badge_color === 'blue' ? 'text-blue-600' :
              'text-emerald-600'
            }>{risk_classification.level}</span>
          </h2>

          <p className="text-xs sm:text-sm text-slate-600 leading-relaxed">
            {risk_classification.description}
          </p>

          {/* Validated Threshold Justification Box */}
          <div className="bg-slate-50 rounded-xl p-3.5 border border-slate-200 text-xs space-y-1">
            <div className="flex items-center justify-between font-bold text-slate-700">
              <span>Decision Boundary Rationale:</span>
              <span className="font-mono text-teal-700">Threshold = {decision_threshold_percentage}%</span>
            </div>
            <p className="text-[11px] text-slate-500 leading-relaxed">
              Standard 50% cutoffs fail in imbalanced clinical cohorts (14.5% positive prevalence). The threshold of 27.94% was established via precision-recall curve F1-optimization during 5-fold cross-validation, achieving the optimal trade-off between sensitivity and precision.
            </p>
          </div>

          <div className="pt-2 flex flex-wrap gap-2 text-[11px]">
            <span className="px-2.5 py-1 rounded-md bg-slate-100 text-slate-700 font-medium">
              CVRI: {engineered_features.cardiovascular_risk_index}
            </span>
            <span className="px-2.5 py-1 rounded-md bg-slate-100 text-slate-700 font-medium">
              Sleep/Sedentary: {engineered_features.sleep_to_sedentary_ratio}
            </span>
            <span className="px-2.5 py-1 rounded-md bg-slate-100 text-slate-700 font-medium">
              Diet-Activity Synergy: {engineered_features.diet_activity_synergy}
            </span>
            <span className="px-2.5 py-1 rounded-md bg-slate-100 text-slate-700 font-medium">
              Obesity-Age: {engineered_features.obesity_age_score}
            </span>
          </div>
        </div>

      </div>

      {/* Individual Factor Contributions (Log-Odds Attribution) */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        
        {/* Risk-Increasing Factors */}
        <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-sm space-y-4">
          <div className="flex items-center space-x-2 text-rose-600 pb-2 border-b border-slate-100">
            <TrendingUp className="w-4 h-4" />
            <h3 className="text-sm font-bold text-slate-900">Key Risk-Increasing Factors (+ Log-Odds)</h3>
          </div>
          
          <div className="space-y-3">
            {top_risk_increasing_factors.map((factor, idx) => (
              <div key={idx} className="space-y-1">
                <div className="flex justify-between text-xs">
                  <span className="font-medium text-slate-700">{factor.label}</span>
                  <span className="font-mono font-bold text-rose-600">+{factor.contribution.toFixed(4)}</span>
                </div>
                <div className="w-full bg-slate-100 h-2 rounded-full overflow-hidden">
                  <div 
                    className="bg-rose-500 h-2 rounded-full transition-all duration-700" 
                    style={{ width: `${Math.min(Math.abs(factor.contribution) * 120, 100)}%` }}
                  />
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Protective Factors */}
        <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-sm space-y-4">
          <div className="flex items-center space-x-2 text-emerald-600 pb-2 border-b border-slate-100">
            <TrendingDown className="w-4 h-4" />
            <h3 className="text-sm font-bold text-slate-900">Key Protective Factors (- Log-Odds)</h3>
          </div>

          <div className="space-y-3">
            {top_protective_factors.map((factor, idx) => (
              <div key={idx} className="space-y-1">
                <div className="flex justify-between text-xs">
                  <span className="font-medium text-slate-700">{factor.label}</span>
                  <span className="font-mono font-bold text-emerald-600">{factor.contribution.toFixed(4)}</span>
                </div>
                <div className="w-full bg-slate-100 h-2 rounded-full overflow-hidden">
                  <div 
                    className="bg-emerald-500 h-2 rounded-full transition-all duration-700" 
                    style={{ width: `${Math.min(Math.abs(factor.contribution) * 120, 100)}%` }}
                  />
                </div>
              </div>
            ))}
          </div>
        </div>

      </div>

      {/* Actionable Modifiable Recommendations */}
      {actionable_recommendations && actionable_recommendations.length > 0 && (
        <div className="bg-white rounded-2xl p-6 sm:p-8 border border-slate-200 shadow-sm space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100">
            <div className="flex items-center space-x-2">
              <Sparkles className="w-4 h-4 text-teal-600" />
              <h3 className="text-sm font-bold text-slate-900">
                Personalized Modifiable Lifestyle Recommendations
              </h3>
            </div>
            <button
              onClick={handleLaunchWhatIf}
              className="text-xs font-semibold text-teal-600 hover:text-teal-700 underline"
            >
              Simulate in What-If Tool &rarr;
            </button>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {actionable_recommendations.map((rec, idx) => (
              <div key={idx} className="bg-slate-50 rounded-xl p-4 border border-slate-200/80 space-y-1.5">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold text-slate-800">{rec.factor}</span>
                  <span className={`text-[10px] px-2 py-0.5 rounded-full font-bold ${
                    rec.priority === 'High' ? 'bg-rose-100 text-rose-800' :
                    rec.priority === 'Medium' ? 'bg-amber-100 text-amber-800' :
                    'bg-blue-100 text-blue-800'
                  }`}>
                    {rec.priority} Priority
                  </span>
                </div>
                <p className="text-xs text-slate-600 leading-relaxed">
                  {rec.advice}
                </p>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Input Summary Grid */}
      {inputSnapshot && (
        <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-sm space-y-4">
          <h3 className="text-xs font-bold text-slate-500 uppercase tracking-wider">
            Patient Assessment Data Summary
          </h3>
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 text-xs">
            <div className="p-3 rounded-lg bg-slate-50 border border-slate-100">
              <span className="text-slate-400 block text-[10px] uppercase font-semibold">Demographics</span>
              <span className="font-bold text-slate-800 block mt-1">{inputSnapshot.age} yrs • {inputSnapshot.sex}</span>
              <span className="text-slate-500 text-[11px]">{inputSnapshot.race_ethnicity}</span>
            </div>
            <div className="p-3 rounded-lg bg-slate-50 border border-slate-100">
              <span className="text-slate-400 block text-[10px] uppercase font-semibold">Genetic &amp; Pedigree</span>
              <span className="font-bold text-slate-800 block mt-1">PRS: {Number(inputSnapshot.t2d_prs).toFixed(2)} SD ({inputSnapshot.genetic_risk_category})</span>
              <span className="text-slate-500 text-[11px]">{inputSnapshot.num_affected_relatives} affected relatives</span>
            </div>
            <div className="p-3 rounded-lg bg-slate-50 border border-slate-100">
              <span className="text-slate-400 block text-[10px] uppercase font-semibold">Lifestyle</span>
              <span className="font-bold text-slate-800 block mt-1">{inputSnapshot.physical_activity_minutes_week} min/wk activity</span>
              <span className="text-slate-500 text-[11px]">Diet Score: {inputSnapshot.diet_quality_score}/100</span>
            </div>
            <div className="p-3 rounded-lg bg-slate-50 border border-slate-100">
              <span className="text-slate-400 block text-[10px] uppercase font-semibold">Clinical</span>
              <span className="font-bold text-slate-800 block mt-1">BMI: {Number(inputSnapshot.bmi).toFixed(1)} kg/m²</span>
              <span className="text-slate-500 text-[11px]">BP: {inputSnapshot.systolic_bp}/{inputSnapshot.diastolic_bp} mmHg</span>
            </div>
          </div>
        </div>
      )}

      {/* Academic Disclaimer Box */}
      <div className="bg-navy-950 text-slate-300 rounded-2xl p-6 border border-navy-800 space-y-2 text-xs leading-relaxed">
        <div className="flex items-center space-x-2 text-amber-300 font-bold">
          <ShieldAlert className="w-4 h-4" />
          <span>Academic Disclaimer &amp; Limitations Notice</span>
        </div>
        <p>
          "This is an academic machine learning research prototype. Its output is an experimental model estimate and is not a medical diagnosis or a substitute for professional medical advice."
        </p>
        <p className="text-slate-400 text-[11px]">
          Results reflect statistical patterns within the 7,000 synthetic participant cohort. Clinical management decisions must never be guided solely by this research software.
        </p>
      </div>

    </div>
  );
}

